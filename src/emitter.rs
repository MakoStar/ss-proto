use std::collections::{BTreeMap, BTreeSet, HashSet};

use crate::model::*;

// 按文件输出
pub fn emit_file(f: &FileIr, syntax_override: Option<Syntax>, source: &str) -> String {
    let syntax = syntax_override.unwrap_or(f.syntax);
    let mut s = String::new();
    let bar = format!("// {}\n", "=".repeat(64));
    s.push_str(&bar);
    s.push_str(&format!("// Generated from {} descriptor file\n", source));
    s.push_str("// DO NOT EDIT - Auto-generated by pb2proto\n");
    s.push_str(&bar);
    s.push('\n');
    s.push_str(&format!("syntax = \"{}\";\n\n", syntax.as_str()));

    emit_file_options(&f.options, &mut s);
    if !f.package.is_empty() {
        s.push_str(&format!("package {};\n\n", f.package));
    }

    let mut seen: HashSet<&str> = HashSet::new();
    for d in &f.dependencies {
        if seen.insert(d.as_str()) {
            if f.public_dependencies.iter().any(|p| p == d) {
                s.push_str(&format!("import public \"{}\";\n", d));
            } else {
                s.push_str(&format!("import \"{}\";\n", d));
            }
        }
    }
    if !f.dependencies.is_empty() {
        s.push('\n');
    }

    emit_top_level_defs(f, &mut s, syntax, 0);
    s
}

// 单文件合并输出
pub fn emit_single_file(
    files: &[FileIr],
    syntax_override: Option<Syntax>,
    package_override: Option<&str>,
    source: &str,
) -> String {
    let syntax = syntax_override.unwrap_or_else(|| dominant_syntax(files));
    let file_names: HashSet<String> = files.iter().map(|f| f.name.clone()).collect();

    let mut s = String::new();
    let bar = format!("// {}\n", "=".repeat(64));
    s.push_str(&bar);
    s.push_str(&format!("// Generated from {} descriptor file\n", source));
    s.push_str("// DO NOT EDIT - Auto-generated by pb2proto\n");
    s.push_str(&bar);
    s.push('\n');
    s.push_str(&format!("syntax = \"{}\";\n\n", syntax.as_str()));

    let packages: BTreeSet<&str> = files
        .iter()
        .map(|f| f.package.as_str())
        .filter(|p| !p.is_empty())
        .collect();

    if packages.len() <= 1 {
        let pkg = package_override
            .or_else(|| packages.iter().next().copied())
            .unwrap_or("");
        if !pkg.is_empty() {
            s.push_str(&format!("package {};\n\n", pkg));
        }
        emit_imports_external(files, &file_names, &mut s);
        for f in files {
            emit_top_level_defs(f, &mut s, syntax, 0);
        }
    } else {
        emit_imports_external(files, &file_names, &mut s);
        let mut root = PkgNode::default();
        for f in files {
            let comps: Vec<&str> = if f.package.is_empty() {
                vec![]
            } else {
                f.package.split('.').collect()
            };
            root.insert(&comps, f);
        }
        emit_pkg_node(&root, None, &mut s, syntax, 0);
        if !s.ends_with('\n') {
            s.push('\n');
        }
    }
    s
}

// 选择主语法
fn dominant_syntax(files: &[FileIr]) -> Syntax {
    let (mut c2, mut c3) = (0, 0);
    for f in files {
        match f.syntax {
            Syntax::Proto2 => c2 += 1,
            Syntax::Proto3 => c3 += 1,
        }
    }
    if c3 >= c2 {
        Syntax::Proto3
    } else {
        Syntax::Proto2
    }
}

// 输出外部依赖
fn emit_imports_external(files: &[FileIr], file_names: &HashSet<String>, s: &mut String) {
    let mut imps: BTreeSet<&str> = BTreeSet::new();
    for f in files {
        for d in &f.dependencies {
            if !file_names.contains(d) {
                imps.insert(d.as_str());
            }
        }
    }
    if !imps.is_empty() {
        for d in imps {
            s.push_str(&format!("import \"{}\";\n", d));
        }
        s.push('\n');
    }
}

// 输出顶层定义
fn emit_top_level_defs(f: &FileIr, s: &mut String, syntax: Syntax, indent: usize) {
    for e in &f.enums {
        emit_enum(e, s, indent);
        s.push('\n');
    }
    for m in &f.messages {
        emit_message(m, s, syntax, indent);
        s.push('\n');
    }
    for svc in &f.services {
        emit_service(svc, s, indent);
        s.push('\n');
    }
    for ext in &f.extensions {
        emit_extend(ext, s, syntax, indent);
        s.push('\n');
    }
}

// 输出枚举
fn emit_enum(e: &Enum, s: &mut String, indent: usize) {
    let pad = "  ".repeat(indent);
    s.push_str(&format!("{}enum {} {{\n", pad, e.name));
    let pad1 = "  ".repeat(indent + 1);
    if e.allow_alias {
        s.push_str(&format!("{}option allow_alias = true;\n", pad1));
    }
    if e.deprecated {
        s.push_str(&format!("{}option deprecated = true;\n", pad1));
    }
    for v in &e.values {
        s.push_str(&format!("{}{} = {};\n", pad1, v.name, v.number));
    }
    s.push_str(&format!("{}}}\n", pad));
}

// 输出消息
fn emit_message(m: &Message, s: &mut String, syntax: Syntax, indent: usize) {
    let pad = "  ".repeat(indent);
    s.push_str(&format!("{}message {} {{\n", pad, m.name));
    let pad1 = "  ".repeat(indent + 1);
    if m.deprecated {
        s.push_str(&format!("{}option deprecated = true;\n", pad1));
    }
    for e in &m.nested_enums {
        emit_enum(e, s, indent + 1);
        s.push('\n');
    }
    for f in &m.fields {
        emit_field(f, s, syntax, indent + 1, false);
    }
    for o in &m.oneofs {
        emit_oneof(o, s, syntax, indent + 1);
    }
    emit_reserved(m, s, indent + 1);
    for ext in &m.extensions {
        emit_extend(ext, s, syntax, indent + 1);
    }
    for nm in &m.nested_messages {
        emit_message(nm, s, syntax, indent + 1);
        s.push('\n');
    }
    s.push_str(&format!("{}}}\n", pad));
}

// 输出字段
fn emit_field(f: &Field, s: &mut String, syntax: Syntax, indent: usize, in_oneof: bool) {
    let pad = "  ".repeat(indent);
    let label = if in_oneof || f.is_map {
        ""
    } else {
        emit_label(f, syntax)
    };
    let type_str = if f.is_map {
        let k = f.map_key.unwrap_or(Scalar::String).as_str();
        let v = match &f.map_value {
            Some(t) => typeref_str(t),
            None => "bytes".to_string(),
        };
        format!("map<{}, {}>", k, v)
    } else {
        typeref_str(&f.kind)
    };

    let mut opts: Vec<String> = Vec::new();
    if syntax == Syntax::Proto2
        && let Some(dv) = &f.default_value
    {
        opts.push(format!("default = {}", format_default(dv, &f.kind)));
    }
    if let Some(p) = f.packed {
        let meaningful = match syntax {
            Syntax::Proto2 => p,
            Syntax::Proto3 => !p,
        };
        if meaningful {
            opts.push(format!("packed = {}", p));
        }
    }
    if f.deprecated {
        opts.push("deprecated = true".to_string());
    }
    let opts_str = if opts.is_empty() {
        String::new()
    } else {
        format!(" [{}]", opts.join(", "))
    };
    s.push_str(&format!(
        "{}{}{} {} = {}{};\n",
        pad, label, type_str, f.name, f.number, opts_str
    ));
}

// 输出标签
fn emit_label(f: &Field, syntax: Syntax) -> &'static str {
    match syntax {
        Syntax::Proto3 => {
            if f.proto3_optional {
                "optional "
            } else if f.label == Label::Repeated {
                "repeated "
            } else {
                ""
            }
        }
        Syntax::Proto2 => match f.label {
            Label::Repeated => "repeated ",
            Label::Required => "required ",
            Label::Optional => "optional ",
        },
    }
}

// 类型引用转字符串
fn typeref_str(k: &TypeRef) -> String {
    match k {
        TypeRef::Scalar(s) => s.as_str().to_string(),
        TypeRef::Message(n) | TypeRef::Enum(n) | TypeRef::Group(n) => n.clone(),
    }
}

// 输出 oneof
fn emit_oneof(o: &Oneof, s: &mut String, syntax: Syntax, indent: usize) {
    let pad = "  ".repeat(indent);
    s.push_str(&format!("{}oneof {} {{\n", pad, o.name));
    for f in &o.fields {
        emit_field(f, s, syntax, indent + 1, true);
    }
    s.push_str(&format!("{}}}\n", pad));
}

// 输出扩展
fn emit_extend(ext: &Extension, s: &mut String, syntax: Syntax, indent: usize) {
    let pad = "  ".repeat(indent);
    s.push_str(&format!("{}extend {} {{\n", pad, ext.extendee));
    for f in &ext.fields {
        emit_field(f, s, syntax, indent + 1, false);
    }
    s.push_str(&format!("{}}}\n", pad));
}

// 输出服务
fn emit_service(svc: &Service, s: &mut String, indent: usize) {
    let pad = "  ".repeat(indent);
    s.push_str(&format!("{}service {} {{\n", pad, svc.name));
    let pad1 = "  ".repeat(indent + 1);
    for m in &svc.methods {
        let cs = if m.client_streaming { "stream " } else { "" };
        let ss = if m.server_streaming { "stream " } else { "" };
        s.push_str(&format!(
            "{}rpc {} ({}{}) returns ({}{});\n",
            pad1, m.name, cs, m.input, ss, m.output
        ));
    }
    s.push_str(&format!("{}}}\n", pad));
}

// 输出保留项
fn emit_reserved(m: &Message, s: &mut String, indent: usize) {
    let pad = "  ".repeat(indent);
    if !m.reserved_ranges.is_empty() {
        let parts: Vec<String> = m
            .reserved_ranges
            .iter()
            .map(|(st, en)| {
                if *en == st + 1 {
                    st.to_string()
                } else {
                    format!("{} to {}", st, en - 1)
                }
            })
            .collect();
        s.push_str(&format!("{}reserved {};\n", pad, parts.join(", ")));
    }
    if !m.reserved_names.is_empty() {
        let names: Vec<String> = m
            .reserved_names
            .iter()
            .map(|n| format!("\"{}\"", n))
            .collect();
        s.push_str(&format!("{}reserved {};\n", pad, names.join(", ")));
    }
}

// 输出文件选项
fn emit_file_options(fo: &FileOptions, s: &mut String) {
    let mut lines: Vec<String> = Vec::new();
    if let Some(v) = &fo.java_package {
        lines.push(format!("option java_package = \"{}\";", v));
    }
    if let Some(v) = &fo.java_outer_classname {
        lines.push(format!("option java_outer_classname = \"{}\";", v));
    }
    if let Some(true) = fo.java_multiple_files {
        lines.push("option java_multiple_files = true;".to_string());
    }
    if let Some(v) = &fo.optimize_for {
        lines.push(format!("option optimize_for = {};", v));
    }
    if let Some(v) = &fo.go_package {
        lines.push(format!("option go_package = \"{}\";", v));
    }
    if let Some(true) = fo.cc_enable_arenas {
        lines.push("option cc_enable_arenas = true;".to_string());
    }
    if let Some(true) = fo.deprecated {
        lines.push("option deprecated = true;".to_string());
    }
    if let Some(v) = &fo.objc_class_prefix {
        lines.push(format!("option objc_class_prefix = \"{}\";", v));
    }
    if let Some(v) = &fo.csharp_namespace {
        lines.push(format!("option csharp_namespace = \"{}\";", v));
    }
    if let Some(v) = &fo.php_namespace {
        lines.push(format!("option php_namespace = \"{}\";", v));
    }
    if let Some(v) = &fo.php_metadata_namespace {
        lines.push(format!("option php_metadata_namespace = \"{}\";", v));
    }
    if let Some(v) = &fo.php_class_prefix {
        lines.push(format!("option php_class_prefix = \"{}\";", v));
    }
    if let Some(v) = &fo.ruby_package {
        lines.push(format!("option ruby_package = \"{}\";", v));
    }
    if let Some(v) = &fo.swift_prefix {
        lines.push(format!("option swift_prefix = \"{}\";", v));
    }
    if !lines.is_empty() {
        for l in lines {
            s.push_str(&l);
            s.push('\n');
        }
        s.push('\n');
    }
}

// 格式化默认值
fn format_default(dv: &str, kind: &TypeRef) -> String {
    match kind {
        TypeRef::Scalar(Scalar::String) => format!("\"{}\"", escape_str(dv)),
        TypeRef::Scalar(Scalar::Bytes) => format!("\"{}\"", escape_str(dv)),
        TypeRef::Scalar(Scalar::Bool) => dv.to_string(),
        TypeRef::Enum(_) => dv.to_string(),
        _ => dv.to_string(),
    }
}

// 转义字符串
fn escape_str(v: &str) -> String {
    let mut o = String::with_capacity(v.len());
    for c in v.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            _ => o.push(c),
        }
    }
    o
}

#[derive(Default)]
struct PkgNode {
    messages: Vec<Message>,
    enums: Vec<Enum>,
    services: Vec<Service>,
    extensions: Vec<Extension>,
    children: BTreeMap<String, PkgNode>,
}

impl PkgNode {
    // 插入包节点
    fn insert(&mut self, comps: &[&str], f: &FileIr) {
        if comps.is_empty() {
            self.messages.extend(f.messages.clone());
            self.enums.extend(f.enums.clone());
            self.services.extend(f.services.clone());
            self.extensions.extend(f.extensions.clone());
        } else {
            self.children
                .entry(comps[0].to_string())
                .or_default()
                .insert(&comps[1..], f);
        }
    }
}

// 递归输出包节点
fn emit_pkg_node(
    node: &PkgNode,
    comp: Option<&str>,
    s: &mut String,
    syntax: Syntax,
    indent: usize,
) {
    let pad = "  ".repeat(indent);
    match comp {
        Some(c) => {
            s.push_str(&format!("{}message {} {{\n", pad, c));
            emit_node_defs(node, s, syntax, indent + 1);
            for (name, child) in &node.children {
                emit_pkg_node(child, Some(name), s, syntax, indent + 1);
            }
            s.push_str(&format!("{}}}\n\n", pad));
        }
        None => {
            emit_node_defs(node, s, syntax, indent);
            for (name, child) in &node.children {
                emit_pkg_node(child, Some(name), s, syntax, indent);
            }
        }
    }
}

// 输出节点定义
fn emit_node_defs(node: &PkgNode, s: &mut String, syntax: Syntax, indent: usize) {
    for e in &node.enums {
        emit_enum(e, s, indent);
        s.push('\n');
    }
    for m in &node.messages {
        emit_message(m, s, syntax, indent);
        s.push('\n');
    }
    for svc in &node.services {
        emit_service(svc, s, indent);
        s.push('\n');
    }
    for ext in &node.extensions {
        emit_extend(ext, s, syntax, indent);
        s.push('\n');
    }
}
